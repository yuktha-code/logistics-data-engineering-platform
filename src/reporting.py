"""Self-contained static HTML evidence dashboard (no JavaScript/CDN dependency)."""
from __future__ import annotations
import html
from pathlib import Path

def render(summary:dict, output:Path) -> None:
    cities=summary.get('city_performance',[])
    overall=summary['overall']
    def val(v):return html.escape(str(v))
    rows=[]
    for c in cities:
        pct=c.get('on_time_pct') or 0
        rows.append('''<tr>
         <td>{city}</td><td>{orders:,}</td><td>{delivered:,}</td>
         <td><div class="pct"><span style="width:{pct:.2f}%"></span></div><b>{pct:.2f}%</b></td>
         <td>{late}</td><td>{cancel}</td></tr>'''.format(
            city=val(c['city']),orders=c['total_orders'],delivered=c['delivered_orders'],
            pct=float(pct),late=val(c['avg_delay_minutes']),cancel=val(c['cancelled_orders'])))
    checks=summary['quality_checks']
    status='PASS' if all(checks.values()) else 'FAIL'
    checks_html=''.join('<li>{}: <b>{}</b></li>'.format(val(k), 'PASS' if v else 'FAIL') for k,v in checks.items())
    source=val(', '.join(summary.get('source_type',[])))
    page='''<!DOCTYPE html><html lang="en"><head><meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>Last-Mile Delivery Reliability | Data Engineering Evidence</title>
    <style>
    :root{{--ink:#14233b;--muted:#63758e;--navy:#172f53;--blue:#2d6cdf;--light:#f4f7fc;--border:#e1e7f1}}
    *{{box-sizing:border-box}}body{{margin:0;background:var(--light);color:var(--ink);font-family:system-ui,Arial,sans-serif}}
    .wrap{{max-width:1120px;margin:0 auto;padding:34px 24px 64px}}h1{{margin:10px 0 5px;font-size:30px}}
    p{{color:var(--muted);line-height:1.6}}.label{{font-size:12px;letter-spacing:1.8px;font-weight:800;color:var(--blue);text-transform:uppercase}}
    .notice{{background:#fff8e9;border-left:4px solid #cb9126;padding:12px 16px;margin:22px 0;font-size:14px}}
    .kpis{{display:grid;grid-template-columns:repeat(auto-fit,minmax(190px,1fr));gap:16px;margin:24px 0}}
    .metric{{background:white;border:1px solid var(--border);padding:20px;border-radius:12px;box-shadow:0 2px 8px #152c4a07}}
    .metric .value{{font-size:29px;font-weight:800;margin:8px 0;color:var(--navy)}}.metric small{{color:var(--muted)}}
    section{{background:white;border:1px solid var(--border);border-radius:12px;padding:22px;margin-top:18px}}
    h2{{font-size:20px;margin:2px 0 12px}}table{{border-collapse:collapse;width:100%;font-size:14px}}th{{background:#edf3fc;text-align:left;padding:12px}}
    td{{padding:11px 12px;border-bottom:1px solid var(--border)}}.pct{{width:100px;height:7px;background:#ecf0f6;border-radius:4px;display:inline-block;vertical-align:middle;margin-right:12px}}
    .pct span{{display:block;height:7px;background:#2d6cdf;border-radius:4px}}ul{{display:grid;grid-template-columns:repeat(auto-fit,minmax(270px,1fr));gap:6px;padding-left:18px;font-size:13px}}
    li b{{color:#177348}}.small{{font-size:12px;color:var(--muted)}}@media(max-width:620px){{table{{font-size:12px}}th,td{{padding:8px 4px}}.pct{{width:42px;margin-right:4px}}}}
    </style></head><body><div class="wrap">
    <div class="label">DE portfolio · ETL / SQL / Data Integrity</div>
    <h1>Last-Mile Delivery Reliability</h1>
    <p>Source: <b>{source}</b> · A reproducible demonstration of dimensional data modeling, validation, and operational reporting.</p>
    <div class="notice"><b>DATA PROVENANCE:</b> Default numbers are generated by a deterministic simulation and are <b>not observations of any logistics operator, real drivers, or real Indian delivery performance</b>. Olist-mode data, if used, represents public Brazilian e-commerce histories.</div>
    <div class="kpis">
      <div class="metric"><div class="label">Orders loaded</div><div class="value">{orders:,}</div><small>Distinct order IDs</small></div>
      <div class="metric"><div class="label">Delivered orders</div><div class="value">{delivered:,}</div><small>Excludes failed/cancelled</small></div>
      <div class="metric"><div class="label">On-time delivery</div><div class="value">{ontime:.2f}%</div><small>Delivered on/before promised time</small></div>
      <div class="metric"><div class="label">Events loaded</div><div class="value">{events:,}</div><small>Deduplicated milestone events</small></div>
    </div>
    <section><h2>Delivery performance by city</h2>
    <table><thead><tr><th>City</th><th>Orders</th><th>Delivered</th><th>On-time share</th><th>Mean late delay (min)</th><th>Cancelled</th></tr></thead><tbody>{table}</tbody></table>
    <p class="small">Mean delay uses a zero-floor: early/on-time deliveries have delay 0. City/state are simulated or drawn from an optional public historical source.</p></section>
    <section><h2>Warehouse quality gates · {status}</h2><ul>{checks}</ul>
    <p class="small">Source parser rejects conflicting duplicate keys, broken relationships and invalid temporal/numeric values. Warehouse checks cover row counts, foreign keys and delivery classification.</p></section>
    <section><h2>What to investigate next</h2><p>City-level SLA distributions; pickup delays vs travel duration; event freshness; late-delivery exceptions; and plan/driver grouping where valid source data exists. Current source does not provide on-duty driver hours, so it cannot calculate true driver utilization.</p></section>
    </div></body></html>'''.format(
        source=source,orders=overall['total_orders'],delivered=overall['delivered'],
        ontime=overall['on_time_pct'] or 0.0,events=summary['warehouse_counts']['events'],
        table=''.join(rows),status=status,checks=checks_html)
    output.write_text(page,encoding='utf-8')
